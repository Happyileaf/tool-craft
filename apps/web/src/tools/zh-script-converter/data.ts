/** 简体 → 繁体（通用）单字表 */
export const S2T_CHARS: Record<string, string> = (() => {
  const table: Record<string, string> = {};
  for (const line of CHAR_PAIRS) {
    for (const token of line.split(/\s+/).filter(Boolean)) {
      const chars = Array.from(token);
      if (chars.length !== 2) {
        throw new Error(`字表条目必须是两个字符：${token}`);
      }
      table[chars[0]] = chars[1];
    }
  }
  return table;
})();

