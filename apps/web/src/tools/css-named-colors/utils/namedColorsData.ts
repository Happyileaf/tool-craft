/** HEX -> RGB */
function hexToRgb(hex: string): { r: number; g: number; b: number } {
  const normalized = hex.slice(1);
  return {
    r: parseInt(normalized.slice(0, 2), 16),
    g: parseInt(normalized.slice(2, 4), 16),
    b: parseInt(normalized.slice(4, 6), 16),
  };
}

/** RGB -> HSL（h: 0-359, s/l: 0-100） */
function rgbToHsl(r: number, g: number, b: number): { h: number; s: number; l: number } {
  const rn = r / 255;
  const gn = g / 255;
  const bn = b / 255;
  const max = Math.max(rn, gn, bn);
  const min = Math.min(rn, gn, bn);
  const delta = max - min;
  let h = 0;

  if (delta !== 0) {
    if (max === rn) {
      h = ((gn - bn) / delta) % 6;
    } else if (max === gn) {
      h = (bn - rn) / delta + 2;
    } else {
      h = (rn - gn) / delta + 4;
    }
    h = Math.round(h * 60);
    if (h < 0) {
      h += 360;
    }
  }

  const l = (max + min) / 2;
  const s = delta === 0 ? 0 : delta / (1 - Math.abs(2 * l - 1));
  return {
    h,
    s: Math.round(s * 100),
    l: Math.round(l * 100),
  };
}

/** 预计算的全部 148 条命名颜色（字母序） */
export const NAMED_COLORS: NamedColor[] = Object.keys(NAMED_COLOR_HEX)
  .sort()
  .map((name) => {
    const hex = NAMED_COLOR_HEX[name]!;
    const rgb = hexToRgb(hex);
    return {
      name,
      hex,
      rgb,
      hsl: rgbToHsl(rgb.r, rgb.g, rgb.b),
      basic: BASIC_COLOR_NAMES.has(name),
    };
  });

/** 名称 -> 记录的快速索引（小写键） */
export const NAMED_COLOR_BY_NAME: Record<string, NamedColor> = Object.fromEntries(
  NAMED_COLORS.map((color) => [color.name, color]),
);
