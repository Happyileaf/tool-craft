/** 单个命名颜色记录 */
export interface NamedColor {
  /** 颜色名称（全小写，作为唯一键） */
  name: string;
  /** 规范 6 位 HEX（小写，含 #） */
  hex: string;
  /** RGB 通道，取值 0-255 */
  rgb: { r: number; g: number; b: number };
  /** HSL：h 取 0-359，s/l 取 0-100（百分比数值） */
  hsl: { h: number; s: number; l: number };
  /** 是否为基础 16 色（Basic CSS colors） */
  basic: boolean;
}

