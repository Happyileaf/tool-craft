/**
 * 常用 HTTP 头字段静态数据（依据 MDN / RFC 9110 系列 / RFC 6265 / RFC 6797 /
 * RFC 6454 / Fetch 标准）。全部为构建时常量，不发起任何网络请求。
 */

/** 头字段方向 */
export type HeaderDirection = 'request' | 'response' | 'both';

/** 分类 id */
export type HeaderCategoryId =
  | 'general'
  | 'request'
  | 'response'
  | 'caching'
  | 'auth-cookie'
  | 'cors'
  | 'security'
  | 'negotiation';

/** 头字段分类 */
export interface HeaderCategory {
  id: HeaderCategoryId;
  label: string;
  labelEn: string;
}

/** 单个头字段条目 */
export interface HttpHeaderEntry {
  /** 标准头名称（连字符形式） */
  name: string;
  /** 中文说明 */
  summary: string;
  /** 方向 */
  direction: HeaderDirection;
  /** 分类 id */
  category: HeaderCategoryId;
  /** 取值语法或枚举 */
  syntax: string;
  /** 示例 */
  example: string;
  /** 关联 RFC / 标准 */
  spec: string;
  /** 是否为 Fetch 禁止修改的请求头（forbidden request header name） */
  forbidden: boolean;
  /** 是否废弃 / 受限 */
  deprecated: boolean;
  /** 常见坑 / 备注 */
  pitfalls: string[];
  /** 搜索关键字 */
  keywords: string[];
}

