import { describe, it, expect } from 'vitest';
import {
  generateGoStruct,
  toGoFieldName,
  inferType,
  mergeTypes,
  createInferContext,
  type GoType,
} from './go-struct';

/**
 * 递归渲染 GoType 节点为类型文本，便于断言 inferType / mergeTypes 结果
 *
 * @param type - Go 类型节点
 * @returns 类型文本
 */
function typeText(type: GoType): string {
  if (type.kind === 'slice') {
    return `[]${typeText(type.element)}`;
  }
  return type.name;
}

describe('toGoFieldName', () => {
  it('snake_case 按词首字母大写', () => {
    expect(toGoFieldName('user_id')).toBe('UserId');
    expect(toGoFieldName('is_active')).toBe('IsActive');
  });

  it('kebab-case 与空格按词首字母大写', () => {
    expect(toGoFieldName('first-name')).toBe('FirstName');
    expect(toGoFieldName('hello world')).toBe('HelloWorld');
  });

  it('camelCase 按大写边界分词后规范', () => {
    expect(toGoFieldName('userName')).toBe('UserName');
    expect(toGoFieldName('HTTPServer')).toBe('HTTPServer');
  });

  it('首字符为数字时追加 X 前缀', () => {
    expect(toGoFieldName('123abc')).toBe('X123Abc');
  });

  it('数字与字母边界也会分词', () => {
    expect(toGoFieldName('user2name')).toBe('User2Name');
  });
});

describe('generateGoStruct - 标量推断', () => {
  it('输入为空或纯空白时返回空串且 struct 数量为 0', () => {
    expect(generateGoStruct('')).toEqual({ output: '', structCount: 0 });
    expect(generateGoStruct('   \n ')).toEqual({ output: '', structCount: 0 });
  });

  it('非法 JSON 抛出含位置信息的中文错误', () => {
    expect(() => generateGoStruct('{ bad json')).toThrowError(/JSON 解析失败/);
  });

  it('基础标量字段推断为 string / int64 / float64 / bool', () => {
    const { output, structCount } = generateGoStruct(
      '{"name":"a","age":1,"score":1.5,"ok":true}',
    );
    expect(output).toContain('type Autogenerated struct {');
    expect(output).toContain('Name string `json:"name"`');
    expect(output).toContain('Age int64 `json:"age"`');
    expect(output).toContain('Score float64 `json:"score"`');
    expect(output).toContain('Ok bool `json:"ok"`');
    expect(structCount).toBe(1);
  });

  it('null 字段推断为 interface{}', () => {
    const { output } = generateGoStruct('{"metadata":null}');
    expect(output).toContain('Metadata interface{} `json:"metadata"`');
  });
});

describe('generateGoStruct - 嵌套对象', () => {
  it('嵌套对象生成具名 struct 并以指针字段引用', () => {
    const { output, structCount } = generateGoStruct('{"addr":{"city":"SH","zip":200000}}');
    expect(output).toContain('Addr *AutogeneratedAddr `json:"addr"`');
    expect(output).toContain('type AutogeneratedAddr struct {');
    expect(output).toContain('City string `json:"city"`');
    expect(output).toContain('Zip int64 `json:"zip"`');
    expect(structCount).toBe(2);
  });

  it('多层嵌套继续提升为具名 struct', () => {
    const { output } = generateGoStruct('{"a":{"b":{"c":1}}}');
    expect(output).toContain('A *AutogeneratedA `json:"a"`');
    expect(output).toContain('B *AutogeneratedAB `json:"b"`');
    expect(output).toContain('C int64 `json:"c"`');
  });
});

describe('generateGoStruct - 数组', () => {
  it('同类型标量数组推断为 []string / []int64', () => {
    const { output } = generateGoStruct('{"tags":["a","b"],"nums":[1,2,3]}');
    expect(output).toContain('Tags []string `json:"tags"`');
    expect(output).toContain('Nums []int64 `json:"nums"`');
  });

  it('对象数组按键并集合并为单个 []T', () => {
    const { output, structCount } = generateGoStruct(
      '{"items":[{"a":1},{"a":2,"b":"x"}]}',
    );
    expect(output).toContain('Items []AutogeneratedItems `json:"items"`');
    expect(output).toContain('type AutogeneratedItems struct {');
    expect(output).toContain('A int64 `json:"a"`');
    expect(output).toContain('B string `json:"b"`');
    expect(structCount).toBe(2);
  });

  it('空数组推断为 []interface{}', () => {
    const { output } = generateGoStruct('{"empty":[]}');
    expect(output).toContain('Empty []interface{} `json:"empty"`');
  });

  it('int 与 float 混合数组提升为 []float64', () => {
    const { output } = generateGoStruct('{"vals":[1,2.5]}');
    expect(output).toContain('Vals []float64 `json:"vals"`');
  });

  it('number 与 string 异构数组降级为 []interface{}', () => {
    const { output } = generateGoStruct('{"mixed":[1,"a"]}');
    expect(output).toContain('Mixed []interface{} `json:"mixed"`');
  });

  it('根数组同样输出具名 slice 类型', () => {
    const { output } = generateGoStruct('[{"id":1},{"id":2,"name":"x"}]');
    expect(output).toContain('type Autogenerated []AutogeneratedItem');
    expect(output).toContain('type AutogeneratedItem struct {');
    expect(output).toContain('Id int64 `json:"id"`');
    expect(output).toContain('Name string `json:"name"`');
  });
});

describe('generateGoStruct - 选项', () => {
  it('omitempty 开启后每个 tag 都携带 ,omitempty', () => {
    const off = generateGoStruct('{"name":"a"}').output;
    expect(off).toContain('`json:"name"`');
    expect(off).not.toContain(',omitempty');

    const on = generateGoStruct('{"name":"a"}', { omitempty: true }).output;
    expect(on).toContain('`json:"name,omitempty"`');
  });

  it('支持自定义根结构名', () => {
    const { output } = generateGoStruct('{"a":1}', { structName: 'User' });
    expect(output).toContain('type User struct {');
    expect(output).toContain('A int64 `json:"a"`');
  });

  it('根结构名非法时抛出错误', () => {
    expect(() => generateGoStruct('{"a":1}', { structName: '1bad' })).toThrowError(
      /根结构名/,
    );
  });
});

describe('generateGoStruct - 重名处理', () => {
  it('同层字段导出后重名时追加数字后缀去重', () => {
    const { output } = generateGoStruct('{"user_id":1,"user-id":2,"userId":3}');
    expect(output).toContain('UserId int64 `json:"user_id"`');
    expect(output).toContain('UserId2 int64 `json:"user-id"`');
    expect(output).toContain('UserId3 int64 `json:"userId"`');
  });

  it('同层嵌套 struct 重名时追加数字后缀', () => {
    const { output } = generateGoStruct('{"user":{"a":1},"User":{"b":2}}');
    expect(output).toContain('type AutogeneratedUser struct {');
    expect(output).toContain('type AutogeneratedUser2 struct {');
    expect(output).toContain('User2 *AutogeneratedUser2 `json:"User"`');
  });
});

describe('inferType / mergeTypes 独立测试', () => {
  it('inferType 覆盖各类标量与 null', () => {
    const context = createInferContext();
    expect(typeText(inferType(null, 'Root', context))).toBe('interface{}');
    expect(typeText(inferType('x', 'Root', context))).toBe('string');
    expect(typeText(inferType(true, 'Root', context))).toBe('bool');
    expect(typeText(inferType(1, 'Root', context))).toBe('int64');
    expect(typeText(inferType(1.5, 'Root', context))).toBe('float64');
  });

  it('mergeTypes 空集合返回 interface{}，数组包装后为空数组元素类型', () => {
    const context = createInferContext();
    expect(typeText(mergeTypes([], 'Root', context))).toBe('interface{}');
    expect(typeText(mergeTypes([[]], 'Root', context))).toBe('[]interface{}');
  });

  it('mergeTypes 标量冲突规则', () => {
    const context = createInferContext();
    expect(typeText(mergeTypes([1, 2.5], 'Root', context))).toBe('float64');
    expect(typeText(mergeTypes([1, 'a'], 'Root', context))).toBe('interface{}');
    expect(typeText(mergeTypes([true, 1], 'Root', context))).toBe('interface{}');
    expect(typeText(mergeTypes([null, 'a'], 'Root', context))).toBe('interface{}');
  });

  it('mergeTypes 数组值整体拍平后合并并包一层 slice', () => {
    const context = createInferContext();
    expect(typeText(mergeTypes([[1], [2.5]], 'Root', context))).toBe('[]float64');
    expect(typeText(mergeTypes([[[1]], [[2.5]]], 'Root', context))).toBe('[][]float64');
  });
});
