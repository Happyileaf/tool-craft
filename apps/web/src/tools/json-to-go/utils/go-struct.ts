/**
 * JSON → Go struct 类型推断纯函数集合。
 *
 * 本模块不依赖 DOM 与 React，仅对输入字符串做解析与递归类型推断，
 * 输出带 `json` tag 的 Go struct 定义文本。
 */
import { DEFAULT_OMITEMPTY, DEFAULT_ROOT_NAME } from '../constants';

/** 合法 Go 标识符匹配规则 */
const IDENTIFIER_PATTERN = /^[A-Za-z_][A-Za-z0-9_]*$/;

/** 按非字母数字字符切词的分隔规则（覆盖 snake_case / kebab-case / 空格等） */
const WORD_SEPARATOR_PATTERN = /[^A-Za-z0-9]+/;

/**
 * 推断出的 Go 类型。
 *
 * - scalar：interface{} / string / bool / int64 / float64
 * - slice：[]T，T 为元素类型
 * - struct：具名 struct，name 为提升到顶层后的类型名
 */
export type GoType =
  | { kind: 'scalar'; name: string }
  | { kind: 'slice'; element: GoType }
  | { kind: 'struct'; name: string };

/**
 * generateGoStruct 的可选配置
 */
export interface GenerateOptions {
  /** 根结构名，默认 Autogenerated，必须为合法 Go 标识符 */
  structName?: string;
  /** 是否为每个字段追加 ,omitempty，默认 false；开启后所有 tag 统一携带 */
  omitempty?: boolean;
}

/**
 * generateGoStruct 的结果
 */
export interface GenerateResult {
  /** 生成的 Go 源码 */
  output: string;
  /** 生成的具名 struct 数量 */
  structCount: number;
}

/**
 * 推断过程中的上下文：已占用的 struct 名称与字段名、已生成的 struct 定义
 */
export interface InferContext {
  /** 已占用的类型名集合，用于重名去重 */
  usedStructNames: Set<string>;
  /** 类型名 → 字段行列表，键的插入顺序即输出顺序 */
  structs: Map<string, string[]>;
  /** 是否为每个 tag 追加 ,omitempty */
  omitempty: boolean;
}

/**
 * 创建推断上下文，供 inferType / mergeTypes 独立单测时使用
 *
 * @param omitempty - 是否为每个 tag 追加 ,omitempty，默认 false
 * @returns 空白推断上下文
 */
export function createInferContext(omitempty = false): InferContext {
  return {
    usedStructNames: new Set<string>(),
    structs: new Map<string, string[]>(),
    omitempty,
  };
}

/**
 * 判断值是否为普通对象（非 null、非数组）
 *
 * @param value - 待判断的值
 * @returns 是否为普通对象
 */
function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * 把任意名称分词后做每个词首字母大写，输出合法 Go 大驼峰名。
 *
 * 处理 snake_case / kebab-case / 空格分隔、camelCase 边界（含连续大写词与数字边界），
 * 剥离非法标识符字符；首字符为数字时追加 X 前缀。
 *
 * @param key - 原始 JSON 键
 * @returns Go 导出字段名（PascalCase）；无法从键中提取词元时返回 Key
 */
export function toGoFieldName(key: string): string {
  // 先按非字母数字字符切词（如 user_id、first-name、hello world）
  const separated = key.split(WORD_SEPARATOR_PATTERN).filter(Boolean);
  const words: string[] = [];
  for (const chunk of separated) {
    // 在连续大写词（HTTPServer）、数字与字母的边界（user2Name、123abc）上进一步分词
    const matches = chunk.match(/[A-Z]+(?=[A-Z][a-z])|[A-Z]?[a-z]+|[A-Z]+|[0-9]+/g);
    if (matches === null) {
      continue;
    }
    for (const word of matches) {
      words.push(word.charAt(0).toUpperCase() + word.slice(1));
    }
  }
  if (words.length === 0) {
    return 'Key';
  }
  let result = words.join('');
  if (/^[0-9]/.test(result)) {
    result = 'X' + result;
  }
  return result;
}

/**
 * 占用一个 struct 名称，重名时追加数字后缀（User → User2 → User3）
 *
 * @param baseName - 期望的基础名称
 * @param context - 推断上下文
 * @returns 去重后实际使用的类型名
 */
function reserveStructName(baseName: string, context: InferContext): string {
  let candidate = baseName;
  let suffix = 2;
  while (context.usedStructNames.has(candidate)) {
    candidate = `${baseName}${suffix}`;
    suffix += 1;
  }
  context.usedStructNames.add(candidate);
  return candidate;
}

/**
 * 推断单个 JSON 值对应的 Go 类型。
 *
 * 标量按 string / bool / int64 / float64 / interface{}（null）推断；
 * 数组与对象会递归调用 mergeTypes / collectStruct 并在上下文中登记新类型。
 *
 * @param value - 已解析的 JSON 值
 * @param baseName - 产生具名 struct / slice 元素命名时使用的基础名称
 * @param context - 推断上下文
 * @returns 推断出的 Go 类型
 */
export function inferType(value: unknown, baseName: string, context: InferContext): GoType {
  if (value === null) {
    return { kind: 'scalar', name: 'interface{}' };
  }
  if (Array.isArray(value)) {
    return mergeTypes([value], baseName, context);
  }
  if (isPlainObject(value)) {
    return collectStruct([value], baseName, context);
  }
  if (typeof value === 'number') {
    return { kind: 'scalar', name: Number.isInteger(value) ? 'int64' : 'float64' };
  }
  if (typeof value === 'string') {
    return { kind: 'scalar', name: 'string' };
  }
  return { kind: 'scalar', name: 'bool' };
}

/**
 * 合并多个 JSON 值的推断结果为单一 Go 类型（数组合并的核心规则）。
 *
 * - 全部为数组：元素整体拍平后继续合并，结果包一层 slice（空数组 → []interface{}）；
 * - 全部为对象：按键并集合并为同一个具名 struct（缺失字段不做特殊标记）；
 * - 标量冲突：int64 与 float64 共存 → float64；number 与 string/bool 或
 *   interface{} 与其他标量共存 → interface{}；空集合 → interface{}；
 * - 不同大类（对象与标量、数组与标量等）完全冲突 → interface{}。
 *
 * @param values - 待合并的值集合（字段值或数组元素）
 * @param baseName - 产生具名 struct 时使用的基础名称
 * @param context - 推断上下文
 * @returns 合并后的 Go 类型
 */
export function mergeTypes(values: unknown[], baseName: string, context: InferContext): GoType {
  return mergeElementTypes(values, baseName, context, 0);
}

/**
 * mergeTypes 的内部实现，depth 标记数组拍平的递归层数：
 * 首层沿用调用方给定的元素基础名，继续向内嵌套时逐层追加 Item 后缀。
 *
 * @param values - 待合并的值集合
 * @param baseName - 产生具名 struct 时使用的基础名称
 * @param context - 推断上下文
 * @param depth - 当前数组拍平深度
 * @returns 合并后的 Go 类型
 */
function mergeElementTypes(
  values: unknown[],
  baseName: string,
  context: InferContext,
  depth: number,
): GoType {
  if (values.length === 0) {
    return { kind: 'scalar', name: 'interface{}' };
  }

  const objectValues: Record<string, unknown>[] = [];
  const arrayElements: unknown[] = [];
  const scalarNames = new Set<string>();
  let hasObject = false;
  let hasArray = false;

  for (const value of values) {
    if (value === null) {
      scalarNames.add('interface{}');
    } else if (Array.isArray(value)) {
      hasArray = true;
      arrayElements.push(...value);
    } else if (isPlainObject(value)) {
      hasObject = true;
      objectValues.push(value);
    } else if (typeof value === 'number') {
      scalarNames.add(Number.isInteger(value) ? 'int64' : 'float64');
    } else if (typeof value === 'string') {
      scalarNames.add('string');
    } else {
      scalarNames.add('bool');
    }
  }

  // 全部为数组：拍平元素递归合并后包一层 slice
  if (hasArray && !hasObject && scalarNames.size === 0) {
    const elementBase = depth === 0 ? baseName : `${baseName}Item`;
    return {
      kind: 'slice',
      element: mergeElementTypes(arrayElements, elementBase, context, depth + 1),
    };
  }

  // 跨大类（对象 / 数组 / 标量）冲突无法用单一 Go 类型表达
  if ([hasObject, hasArray, scalarNames.size > 0].filter(Boolean).length > 1) {
    return { kind: 'scalar', name: 'interface{}' };
  }

  if (hasObject) {
    return collectStruct(objectValues, baseName, context);
  }
  if (scalarNames.size === 1) {
    return { kind: 'scalar', name: Array.from(scalarNames)[0] as string };
  }
  if (scalarNames.has('interface{}')) {
    return { kind: 'scalar', name: 'interface{}' };
  }
  if (scalarNames.has('int64') && scalarNames.has('float64')) {
    return { kind: 'scalar', name: 'float64' };
  }
  // number 与 string / bool 等标量冲突
  return { kind: 'scalar', name: 'interface{}' };
}

/**
 * 合并一组对象为单个具名 struct：取键的并集，同名字段递归合并类型。
 *
 * 生成的字段中，对象引用以指针（*T）表达可空语义，数组元素为对象时使用 []T。
 *
 * @param objects - 需要合并的对象集合
 * @param baseName - 该 struct 期望的基础名称
 * @param context - 推断上下文
 * @returns 生成的 struct 类型
 */
function collectStruct(
  objects: Record<string, unknown>[],
  baseName: string,
  context: InferContext,
): GoType {
  const name = reserveStructName(baseName, context);
  // 先占位以保证输出顺序为「父 struct 在前」，随后再回填字段行
  context.structs.set(name, []);

  const keys: string[] = [];
  const seenKeys = new Set<string>();
  for (const object of objects) {
    for (const key of Object.keys(object)) {
      if (!seenKeys.has(key)) {
        seenKeys.add(key);
        keys.push(key);
      }
    }
  }

  const lines: string[] = [];
  const usedFieldNames = new Set<string>();
  for (const key of keys) {
    const presentValues: unknown[] = [];
    for (const object of objects) {
      if (Object.prototype.hasOwnProperty.call(object, key)) {
        presentValues.push(object[key]);
      }
    }

    const fieldBase = toGoFieldName(key);
    let fieldName = fieldBase;
    let fieldSuffix = 2;
    while (usedFieldNames.has(fieldName)) {
      fieldName = `${fieldBase}${fieldSuffix}`;
      fieldSuffix += 1;
    }
    usedFieldNames.add(fieldName);

    let type = mergeTypes(presentValues, `${name}${fieldBase}`, context);
    // 嵌套对象字段以指针表达可空语义，数组元素中的对象保持 []T
    if (type.kind === 'struct') {
      type = { kind: 'scalar', name: `*${type.name}` };
    }

    lines.push(renderFieldLine(fieldName, renderType(type), key, context.omitempty));
  }

  context.structs.set(name, lines);
  return { kind: 'struct', name };
}

/**
 * 把 Go 类型节点渲染为类型文本
 *
 * @param type - Go 类型节点
 * @returns 可直接写入字段定义的类型文本
 */
function renderType(type: GoType): string {
  if (type.kind === 'slice') {
    return `[]${renderType(type.element)}`;
  }
  return type.name;
}

/**
 * 渲染单个 struct 字段行
 *
 * @param fieldName - 导出字段名
 * @param typeText - 字段类型文本
 * @param jsonKey - 原始 JSON 键，原样写入 json tag
 * @param omitempty - 是否追加 ,omitempty（全局开关，简化规则：统一携带）
 * @returns 字段源码行
 */
function renderFieldLine(
  fieldName: string,
  typeText: string,
  jsonKey: string,
  omitempty: boolean,
): string {
  const tagValue = omitempty ? `${jsonKey},omitempty` : jsonKey;
  return `${fieldName} ${typeText} \`json:"${tagValue}"\``;
}

/**
 * 渲染单个 struct 定义
 *
 * @param name - struct 名称
 * @param lines - 字段行列表
 * @returns 完整的 type 源码块
 */
function renderStruct(name: string, lines: string[]): string {
  if (lines.length === 0) {
    return `type ${name} struct {}`;
  }
  const body = lines.map((line) => `    ${line}`).join('\n');
  return `type ${name} struct {\n${body}\n}`;
}

/**
 * 解析 JSON 文本并生成带 json tag 的 Go struct 定义。
 *
 * 整数统一推断为 int64（遵循 json-to-go.org 惯例），null 推断为 interface{}，
 * 嵌套对象提升为顶层具名 struct 并以指针字段引用。输入为空或纯空白时返回空串。
 *
 * @param jsonText - JSON 文本
 * @param options - 可选配置（根结构名 structName、omitempty 开关）
 * @returns 生成的 Go 源码与 struct 数量
 * @throws 当输入不是合法 JSON 或根结构名不是合法 Go 标识符时抛出可读错误
 */
export function generateGoStruct(
  jsonText: string,
  options: GenerateOptions = {},
): GenerateResult {
  const trimmed = jsonText.trim();
  if (trimmed === '') {
    return { output: '', structCount: 0 };
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(trimmed);
  } catch (caught) {
    const detail = caught instanceof Error ? caught.message : String(caught);
    throw new Error('JSON 解析失败：' + detail);
  }

  let rootName = (options.structName ?? DEFAULT_ROOT_NAME).trim() || DEFAULT_ROOT_NAME;
  if (!IDENTIFIER_PATTERN.test(rootName)) {
    throw new Error('根结构名必须是合法的 Go 标识符：' + rootName);
  }
  // 首字母大写以保证根类型可导出
  rootName = rootName.charAt(0).toUpperCase() + rootName.slice(1);

  const omitempty = options.omitempty ?? DEFAULT_OMITEMPTY;
  const context = createInferContext(omitempty);

  const blocks: string[] = [
    '// 由 JSON 自动生成：整数统一推断为 int64，null 推断为 interface{}。',
  ];
  if (omitempty) {
    blocks.push('// omitempty 已开启：所有字段的 json tag 统一携带 ,omitempty。');
  }

  let rootType: GoType;
  if (isPlainObject(parsed)) {
    rootType = collectStruct([parsed], rootName, context);
  } else {
    context.usedStructNames.add(rootName);
    rootType = Array.isArray(parsed)
      ? mergeTypes([parsed], `${rootName}Item`, context)
      : inferType(parsed, rootName, context);
    blocks.push(`type ${rootName} ${renderType(rootType)}`);
  }

  for (const [name, lines] of context.structs) {
    blocks.push(renderStruct(name, lines));
  }

  return { output: blocks.join('\n\n'), structCount: context.structs.size };
}
