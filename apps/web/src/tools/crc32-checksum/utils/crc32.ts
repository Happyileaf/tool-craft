/**
 * 计算字符串的 CRC32 校验和
 * @param str - 输入字符串
 * @returns CRC32 校验和的十六进制小写字符串
 */
export function calculateCRC32(str: string): string {
  // 转换为 UTF-8 字节数组
  const encoder = new TextEncoder();
  const bytes = encoder.encode(str);

  let crc = 0 ^ (-1);

  for (const byte of bytes) {
    const tableIndex = (crc ^ byte) & 0xff;
    crc = (crc >>> 8) ^ CRC_TABLE[tableIndex]!;
  }

  // 反转并转换为十六进制
  const result = (crc ^ (-1)) >>> 0;
  return result.toString(16).toLowerCase();
}
