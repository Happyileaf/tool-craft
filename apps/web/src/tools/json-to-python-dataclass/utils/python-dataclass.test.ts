import { describe, expect, it } from 'vitest';
import {
  createInferContext,
  generatePythonDataclass,
  mergeTypes,
  toPythonClassName,
  toPythonFieldName,
} from './python-dataclass';

describe('toPythonFieldName', () => {
  it('保留下划线并转换 camelCase 与连字符', () => {
    expect(toPythonFieldName('user_id')).toBe('user_id');
    expect(toPythonFieldName('userId')).toBe('user_id');
    expect(toPythonFieldName('HTTPServer')).toBe('http_server');
    expect(toPythonFieldName('last-login')).toBe('last_login');
  });

  it('命中保留字时追加下划线，数字开头前置下划线', () => {
    expect(toPythonFieldName('class')).toBe('class_');
    expect(toPythonFieldName('123abc')).toBe('_123_abc');
    expect(toPythonFieldName('!!!')).toBe('field');
  });
});

describe('toPythonClassName', () => {
  it('转换为 PascalCase', () => {
    expect(toPythonClassName('user_id')).toBe('UserId');
    expect(toPythonClassName('last-login')).toBe('LastLogin');
    expect(toPythonClassName('123abc')).toBe('X123Abc');
    expect(toPythonClassName('!!!')).toBe('Key');
  });
});

describe('mergeTypes', () => {
  it('空数组退化为裸 list', () => {
    const ctx = createInferContext();
    expect(mergeTypes([], 'Item', ctx)).toEqual({ kind: 'list' });
  });

  it('int 与 float 合并为 float', () => {
    const ctx = createInferContext();
    expect(mergeTypes([1, 2.5, 3], 'Item', ctx)).toEqual({
      kind: 'scalar',
      name: 'float',
    });
  });

  it('不同标量合并为 Any，null 与标量合并为 Optional', () => {
    const anyCtx = createInferContext();
    expect(mergeTypes([1, 'two'], 'Item', anyCtx)).toEqual({
      kind: 'scalar',
      name: 'Any',
    });

    const optCtx = createInferContext();
    expect(mergeTypes(['a', null], 'Item', optCtx)).toEqual({
      kind: 'optional',
      element: { kind: 'scalar', name: 'str' },
    });
  });

  it('全为 null 时推断为 None', () => {
    const ctx = createInferContext();
    expect(mergeTypes([null, null], 'Item', ctx)).toEqual({
      kind: 'scalar',
      name: 'None',
    });
  });

  it('对象数组合并为同一个具名类（字段并集）', () => {
    const ctx = createInferContext();
    const type = mergeTypes(
      [
        { name: 'Alan', age: 41 },
        { name: 'Grace', age: 45, title: 'Admiral' },
      ],
      'Friend',
      ctx,
    );
    expect(type).toEqual({ kind: 'class', name: 'Friend' });
    const fields = ctx.classes.get('Friend') ?? [];
    expect(fields.map((field) => field.key)).toEqual(['name', 'age', 'title']);
    expect(fields[2]?.absent).toBe(true);
  });

  it('数组拍平：嵌套数组整体合并', () => {
    const ctx = createInferContext();
    expect(
      mergeTypes([[1, 2], [3, 4]], 'Item', ctx),
    ).toEqual({ kind: 'list', element: { kind: 'scalar', name: 'int' } });
  });

  it('类名冲突追加数字后缀', () => {
    const ctx = createInferContext();
    expect(mergeTypes([{ a: 1 }], 'Node', ctx)).toEqual({ kind: 'class', name: 'Node' });
    expect(mergeTypes([{ a: 1 }], 'Node', ctx)).toEqual({ kind: 'class', name: 'Node2' });
  });
});

describe('generatePythonDataclass - dataclass 风格', () => {
  it('简单标量对象的确定性输出', () => {
    const result = generatePythonDataclass('{"name": "Ada", "age": 36}');
    expect(result.classCount).toBe(1);
    expect(result.output).toBe(
      [
        'from __future__ import annotations',
        '',
        'from dataclasses import asdict, dataclass',
        '',
        '# 由 JSON 自动生成：null 字段以 Optional 表达，空数组退化为 list。',
        '',
        '@dataclass',
        'class Autogenerated:',
        '    name: str',
        '    age: int',
        '',
        '    @classmethod',
        '    def from_dict(cls, d: dict) -> "Autogenerated":',
        '        return cls(',
        '            name=d["name"],',
        '            age=d["age"],',
        '        )',
        '',
        '    def to_dict(self) -> dict:',
        '        return asdict(self)',
      ].join('\n'),
    );
  });

  it('嵌套对象提升为独立类，父类在前', () => {
    const result = generatePythonDataclass(
      '{"profile": {"email": "a@b.com", "verified": true}}',
    );
    expect(result.output).toContain('class Autogenerated:');
    expect(result.output).toContain('profile: AutogeneratedProfile');
    expect(result.output).toContain('class AutogeneratedProfile:');
    expect(result.output.indexOf('class Autogenerated:')).toBeLessThan(
      result.output.indexOf('class AutogeneratedProfile:'),
    );
    expect(result.output).toContain(
      'profile=AutogeneratedProfile.from_dict(d["profile"])',
    );
  });

  it('异构对象数组：缺失字段为 Optional + None 默认值，from_dict 走 get', () => {
    const result = generatePythonDataclass(
      '{"friends": [{"name": "Alan", "age": 41}, {"name": "Grace", "age": 45, "title": "Admiral"}]}',
    );
    expect(result.output).toContain('from typing import Optional');
    expect(result.output).toContain('class AutogeneratedFriends:');
    expect(result.output).toContain('    name: str');
    expect(result.output).toContain('    age: int');
    expect(result.output).toContain('    title: Optional[str] = None');
    expect(result.output).toContain('title=None if d.get("title") is None else d.get("title")');
    expect(result.output).toContain(
      'friends=[AutogeneratedFriends.from_dict(item) for item in d["friends"]]',
    );
  });

  it('空数组退化为裸 list，非空数组推断元素类型', () => {
    const result = generatePythonDataclass('{"notes": [], "counts": [1, 2, 3]}');
    expect(result.output).toContain('    notes: list');
    expect(result.output).toContain('    counts: list[int]');
  });

  it('null 与混合数组：全 null 为 None，异构标量数组为 list[Any]', () => {
    const result = generatePythonDataclass('{"metadata": null, "mixed": [1, "two", null]}');
    expect(result.output).toContain('    metadata: None');
    expect(result.output).toContain('    mixed: list[Any]');
    expect(result.output).toContain('from typing import Any');
  });

  it('null + 标量字段推断为 Optional[T]', () => {
    const result = generatePythonDataclass('{"nickname": null, "nickname2": "x"}', {
      className: 'Root',
    });
    // 同一字段只出现 null 时为 None
    expect(result.output).toContain('    nickname: None');
    expect(result.output).toContain('    nickname_2: str');

    const merged = generatePythonDataclass('{"values": ["a", null]}');
    expect(merged.output).toContain('    values: list[Optional[str]]');
  });

  it('下划线 / 连字符键名规范化为 snake_case，重名追加后缀', () => {
    const result = generatePythonDataclass(
      '{"user-id": 1, "user_id": 2, "last-login": "x"}',
    );
    expect(result.output).toContain('    user_id: int');
    expect(result.output).toContain('    user_id_2: int');
    expect(result.output).toContain('    last_login: str');
    // from_dict 保留原始键
    expect(result.output).toContain('d["user-id"]');
  });

  it('关闭辅助方法后无方法定义与 asdict 导入', () => {
    const result = generatePythonDataclass('{"a": 1}', { helpers: false });
    expect(result.output).not.toContain('from_dict');
    expect(result.output).not.toContain('to_dict');
    expect(result.output).toContain('from dataclasses import dataclass');
  });

  it('根类名规范化为首字母大写的合法标识符', () => {
    const result = generatePythonDataclass('{"a": 1}', { className: 'my_model' });
    expect(result.output).toContain('class MyModel:');
  });

  it('必填字段排在带默认值的可选字段之前', () => {
    const result = generatePythonDataclass(
      '{"items": [{"name": "a", "extra": 1}, {"name": "b"}]}',
    );
    const classStart = result.output.indexOf('class AutogeneratedItems:');
    const namePos = result.output.indexOf('    name: str', classStart);
    const extraPos = result.output.indexOf('    extra: Optional[int] = None', classStart);
    expect(namePos).toBeGreaterThan(-1);
    expect(extraPos).toBeGreaterThan(namePos);
  });
});

describe('generatePythonDataclass - typeddict 风格', () => {
  it('输出 TypedDict，缺失键标记 NotRequired', () => {
    const result = generatePythonDataclass(
      '{"friends": [{"name": "Alan", "title": null}, {"name": "Grace", "title": "Admiral"}, {"name": "Lin"}]}',
      { style: 'typeddict' },
    );
    expect(result.output).toContain(
      'from typing import TypedDict, Optional, NotRequired  # NotRequired 需 Python 3.11+',
    );
    expect(result.output).toContain('class Autogenerated(TypedDict):');
    expect(result.output).toContain('    name: str');
    // title 在部分对象缺失（NotRequired），且取值含 null（Optional）
    expect(result.output).toContain('    title: NotRequired[Optional[str]]');
    expect(result.output).not.toContain('@dataclass');
    expect(result.output).not.toContain('from_dict');
  });

  it('无缺失键时不导入 NotRequired，null 仍为 Optional', () => {
    const result = generatePythonDataclass('{"a": 1, "b": ["x", null]}', {
      style: 'typeddict',
    });
    expect(result.output).toContain('from typing import TypedDict, Optional');
    expect(result.output).not.toContain('NotRequired[');
    expect(result.output).toContain('    b: list[Optional[str]]');
  });
});

describe('generatePythonDataclass - 根数组与边界', () => {
  it('根为对象数组：生成元素类并输出类型别名', () => {
    const result = generatePythonDataclass('[{"id": 1}, {"id": 2, "name": "x"}]');
    expect(result.classCount).toBe(1);
    expect(result.output).toContain('class AutogeneratedItem:');
    expect(result.output).toContain('Autogenerated = list[AutogeneratedItem]');
  });

  it('根为标量数组', () => {
    const result = generatePythonDataclass('[1, 2, 3]');
    expect(result.classCount).toBe(0);
    expect(result.output.trimEnd().endsWith('Autogenerated = list[int]')).toBe(true);
  });

  it('空白输入返回空串', () => {
    expect(generatePythonDataclass('   ')).toEqual({ output: '', classCount: 0 });
  });

  it('非法 JSON 抛出中文错误', () => {
    expect(() => generatePythonDataclass('{invalid}')).toThrow(/JSON 解析失败/);
  });

  it('非法根类名抛出中文错误', () => {
    expect(() => generatePythonDataclass('{"a":1}', { className: '123' })).toThrow(
      /合法的 Python 标识符/,
    );
  });
});

describe('generatePythonDataclass - 固定样本快照', () => {
  const sample = `{
  "code": 0,
  "data": {
    "user_id": 1001,
    "profile": { "email": "ada@example.com", "verified": true },
    "friends": [
      { "name": "Alan", "age": 41 },
      { "name": "Grace", "age": 45, "title": "Admiral" }
    ]
  },
  "metadata": null,
  "notes": []
}`;

  it('dataclass 风格快照确定性', () => {
    expect(generatePythonDataclass(sample).output).toBe(
      [
        'from __future__ import annotations',
        '',
        'from dataclasses import asdict, dataclass',
        'from typing import Optional',
        '',
        '# 由 JSON 自动生成：null 字段以 Optional 表达，空数组退化为 list。',
        '',
        '@dataclass',
        'class Autogenerated:',
        '    code: int',
        '    data: AutogeneratedData',
        '    metadata: None',
        '    notes: list',
        '',
        '    @classmethod',
        '    def from_dict(cls, d: dict) -> "Autogenerated":',
        '        return cls(',
        '            code=d["code"],',
        '            data=AutogeneratedData.from_dict(d["data"]),',
        '            metadata=d["metadata"],',
        '            notes=d["notes"],',
        '        )',
        '',
        '    def to_dict(self) -> dict:',
        '        return asdict(self)',
        '',
        '@dataclass',
        'class AutogeneratedData:',
        '    user_id: int',
        '    profile: AutogeneratedDataProfile',
        '    friends: list[AutogeneratedDataFriends]',
        '',
        '    @classmethod',
        '    def from_dict(cls, d: dict) -> "AutogeneratedData":',
        '        return cls(',
        '            user_id=d["user_id"],',
        '            profile=AutogeneratedDataProfile.from_dict(d["profile"]),',
        '            friends=[AutogeneratedDataFriends.from_dict(item) for item in d["friends"]],',
        '        )',
        '',
        '@dataclass',
        'class AutogeneratedDataProfile:',
        '    email: str',
        '    verified: bool',
        '',
        '    @classmethod',
        '    def from_dict(cls, d: dict) -> "AutogeneratedDataProfile":',
        '        return cls(',
        '            email=d["email"],',
        '            verified=d["verified"],',
        '        )',
        '',
        '@dataclass',
        'class AutogeneratedDataFriends:',
        '    name: str',
        '    age: int',
        '    title: Optional[str] = None',
        '',
        '    @classmethod',
        '    def from_dict(cls, d: dict) -> "AutogeneratedDataFriends":',
        '        return cls(',
        '            name=d["name"],',
        '            age=d["age"],',
        '            title=None if d.get("title") is None else d.get("title"),',
        '        )',
      ].join('\n'),
    );
  });

  it('同一输入重复生成结果完全一致', () => {
    const first = generatePythonDataclass(sample).output;
    const second = generatePythonDataclass(sample).output;
    expect(second).toBe(first);
  });
});
