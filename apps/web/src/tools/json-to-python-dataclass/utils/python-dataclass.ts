/**
 * JSON → Python @dataclass / TypedDict 类型推断纯函数集合。
 *
 * 本模块不依赖 DOM 与 React，仅对输入字符串做解析与递归类型推断，
 * 输出可直接粘贴到 Python 工程中的数据模型源码。
 */
import { DEFAULT_CLASS_NAME } from '../constants';

/** 合法 Python 标识符匹配规则 */
const IDENTIFIER_PATTERN = /^[A-Za-z_][A-Za-z0-9_]*$/;

/** 按非字母数字字符切词的分隔规则（覆盖 snake_case / kebab-case / 空格等） */
const WORD_SEPARATOR_PATTERN = /[^A-Za-z0-9]+/;

/**
 * Python 保留字集合，字段名命中时追加下划线后缀（class → class_）。
 */
const PYTHON_KEYWORDS = new Set([
  'False',
  'None',
  'True',
  'and',
  'as',
  'assert',
  'async',
  'await',
  'break',
  'class',
  'continue',
  'def',
  'del',
  'elif',
  'else',
  'except',
  'finally',
  'for',
  'from',
  'global',
  'if',
  'import',
  'in',
  'is',
  'lambda',
  'nonlocal',
  'not',
  'or',
  'pass',
  'raise',
  'return',
  'try',
  'while',
  'with',
  'yield',
]);

/** 标量类型名集合 */
type ScalarName = 'str' | 'int' | 'float' | 'bool' | 'None' | 'Any';

/**
 * 输出风格。
 *
 * - dataclass：@dataclass 类，可缺省字段给 None 默认值，可附 from_dict / to_dict
 * - typeddict：typing.TypedDict 类，可缺省键标记 NotRequired
 */
export type OutputStyle = 'dataclass' | 'typeddict';

/**
 * generatePythonDataclass 的可选配置
 */
export interface GenerateOptions {
  /** 根类名，默认 Autogenerated，必须为合法 Python 标识符 */
  className?: string;
  /** 输出风格，默认 dataclass */
  style?: OutputStyle;
  /** 是否生成 from_dict / to_dict 辅助方法（仅 dataclass 风格），默认 true */
  helpers?: boolean;
}

/**
 * generatePythonDataclass 的结果
 */
export interface GenerateResult {
  /** 生成的 Python 源码 */
  output: string;
  /** 生成的具名类数量（不含类型别名） */
  classCount: number;
}

/**
 * 推断出的 Python 类型节点。
 *
 * - scalar：str / int / float / bool / None / Any
 * - optional：Optional[T]，Any / None 不会再被包装
 * - list：list[T]，element 缺省时退化为裸 list（空数组）
 * - class：具名 @dataclass / TypedDict，name 为提升到顶层后的类名
 */
export type PyType =
  | { kind: 'scalar'; name: ScalarName }
  | { kind: 'optional'; element: PyType }
  | { kind: 'list'; element?: PyType }
  | { kind: 'class'; name: string };

/**
 * 类中的单个字段描述
 */
interface FieldSpec {
  /** 原始 JSON 键 */
  key: string;
  /** 规范化后的 Python 字段名 */
  name: string;
  /** 合并后的类型节点（null 已反映为 optional 包装） */
  type: PyType;
  /** 是否在部分合并对象中缺失（dataclass 给默认值，TypedDict 标 NotRequired） */
  absent: boolean;
}

/**
 * 推断过程中的上下文：已占用类名、已生成类的字段表
 */
export interface InferContext {
  /** 已占用的类名集合，用于重名去重 */
  usedClassNames: Set<string>;
  /** 类名 → 字段表，键的插入顺序即输出顺序（父类在前） */
  classes: Map<string, FieldSpec[]>;
}

/**
 * 渲染期状态：登记 typing 导入项与 NotRequired 使用情况
 */
interface RenderState {
  needAny: boolean;
  needOptional: boolean;
  needNotRequired: boolean;
}

/**
 * 创建空白推断上下文，供独立单测使用
 *
 * @returns 空白推断上下文
 */
export function createInferContext(): InferContext {
  return { usedClassNames: new Set<string>(), classes: new Map<string, FieldSpec[]>() };
}

/**
 * 把任意名称分词为小写词元数组。
 *
 * 处理 snake_case / kebab-case / 空格分隔与 camelCase 边界
 * （含连续大写词与数字边界），剥离非法标识符字符。
 *
 * @param key - 原始 JSON 键
 * @returns 词元数组；无法提取时返回空数组
 */
function splitWords(key: string): string[] {
  const separated = key.split(WORD_SEPARATOR_PATTERN).filter(Boolean);
  const words: string[] = [];
  for (const chunk of separated) {
    const matches = chunk.match(/[A-Z]+(?=[A-Z][a-z])|[A-Z]?[a-z]+|[A-Z]+|[0-9]+/g);
    if (matches === null) {
      continue;
    }
    words.push(...matches);
  }
  return words;
}

/**
 * 把任意 JSON 键转换为合法 Python snake_case 字段名。
 *
 * 命中保留字时追加下划线；首字符为数字时前置下划线；无法提取词元时返回 field。
 *
 * @param key - 原始 JSON 键
 * @returns snake_case 字段名
 */
export function toPythonFieldName(key: string): string {
  const words = splitWords(key).map((word) => word.toLowerCase());
  let result = words.length === 0 ? 'field' : words.join('_');
  if (/^[0-9]/.test(result)) {
    result = '_' + result;
  }
  if (PYTHON_KEYWORDS.has(result)) {
    result = result + '_';
  }
  return result;
}

/**
 * 把任意 JSON 键转换为合法 Python PascalCase 类名。
 *
 * 首字符为数字时前置 X；无法提取词元时返回 Key。
 *
 * @param key - 原始 JSON 键
 * @returns PascalCase 类名
 */
export function toPythonClassName(key: string): string {
  const words = splitWords(key).map(
    (word) => word.charAt(0).toUpperCase() + word.slice(1),
  );
  let result = words.length === 0 ? 'Key' : words.join('');
  if (/^[0-9]/.test(result)) {
    result = 'X' + result;
  }
  return result;
}

/**
 * 用 Optional 包装类型；Any 与 None 不再包装（Optional 化无意义），
 * 已是 optional 节点时幂等返回。
 *
 * @param type - 原始类型节点
 * @returns 包装后的类型节点
 */
function wrapOptional(type: PyType): PyType {
  if (type.kind === 'optional') {
    return type;
  }
  if (type.kind === 'scalar' && (type.name === 'Any' || type.name === 'None')) {
    return type;
  }
  return { kind: 'optional', element: type };
}

/**
 * 判断值是否为普通对象（非 null、非数组）
 *
 * @param value - 待判断的值
 * @returns 是否为普通对象
 */
function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * 占用一个类名，重名时追加数字后缀（User → User2 → User3）。
 *
 * @param baseName - 期望的基础名称
 * @param context - 推断上下文
 * @returns 去重后实际使用的类名
 */
function reserveClassName(baseName: string, context: InferContext): string {
  let candidate = baseName;
  let suffix = 2;
  while (context.usedClassNames.has(candidate)) {
    candidate = `${baseName}${suffix}`;
    suffix += 1;
  }
  context.usedClassNames.add(candidate);
  return candidate;
}

/**
 * 合并多个 JSON 值的推断结果为单一 Python 类型（数组合并的核心规则）。
 *
 * - 全部为数组：元素整体拍平后继续合并，结果包一层 list（空数组 → 裸 list）；
 * - 全部为对象：按键并集合并为同一个具名类；
 * - 标量冲突：int 与 float 共存 → float；其余不同标量共存 → Any；
 * - 含 null：标量结果以 Optional 表达（全为 null → None）；
 * - 不同大类（对象与标量、数组与标量等）完全冲突 → Any。
 *
 * @param values - 待合并的值集合（字段值或数组元素）
 * @param baseName - 产生具名类时使用的基础名称
 * @param context - 推断上下文
 * @returns 合并后的类型节点
 */
export function mergeTypes(values: unknown[], baseName: string, context: InferContext): PyType {
  return mergeElementTypes(values, baseName, context, 0);
}

/**
 * mergeTypes 的内部实现，depth 标记数组拍平的递归层数：
 * 首层沿用调用方给定的元素基础名，继续向内嵌套时逐层追加 Item 后缀。
 *
 * @param values - 待合并的值集合
 * @param baseName - 产生具名类时使用的基础名称
 * @param context - 推断上下文
 * @param depth - 当前数组拍平深度
 * @returns 合并后的类型节点
 */
function mergeElementTypes(
  values: unknown[],
  baseName: string,
  context: InferContext,
  depth: number,
): PyType {
  if (values.length === 0) {
    return { kind: 'list' };
  }

  const objectValues: Record<string, unknown>[] = [];
  const arrayElements: unknown[] = [];
  const scalarKinds = new Set<ScalarName>();
  let hasObject = false;
  let hasArray = false;
  let hasNull = false;

  for (const value of values) {
    if (value === null) {
      hasNull = true;
    } else if (Array.isArray(value)) {
      hasArray = true;
      arrayElements.push(...value);
    } else if (isPlainObject(value)) {
      hasObject = true;
      objectValues.push(value);
    } else if (typeof value === 'number') {
      scalarKinds.add(Number.isInteger(value) ? 'int' : 'float');
    } else if (typeof value === 'string') {
      scalarKinds.add('str');
    } else {
      scalarKinds.add('bool');
    }
  }

  // 全部为数组：拍平一层元素后递归合并，再统一包一层 list，
  // 保持嵌套数组的层级（[[1]] → list[list[int]]）；
  // 首层拍平后为空（如字段 "notes": []）时元素类型未知，退化为裸 list
  if (hasArray && !hasObject && scalarKinds.size === 0 && !hasNull) {
    if (depth === 0 && arrayElements.length === 0) {
      return { kind: 'list' };
    }
    const elementBase = depth === 0 ? baseName : `${baseName}Item`;
    return {
      kind: 'list',
      element: mergeElementTypes(arrayElements, elementBase, context, depth + 1),
    };
  }

  // 跨大类（对象 / 数组 / 标量或 null）冲突无法用单一 Python 类型表达 → Any
  if ([hasObject, hasArray, scalarKinds.size > 0 || hasNull].filter(Boolean).length > 1) {
    return { kind: 'scalar', name: 'Any' };
  }

  if (hasObject) {
    return collectClass(objectValues, baseName, context);
  }

  let scalar: PyType;
  if (scalarKinds.size === 0) {
    scalar = { kind: 'scalar', name: 'None' };
  } else if (scalarKinds.size === 1) {
    const name = Array.from(scalarKinds)[0] as ScalarName;
    scalar = { kind: 'scalar', name };
  } else if (scalarKinds.size === 2 && scalarKinds.has('int') && scalarKinds.has('float')) {
    scalar = { kind: 'scalar', name: 'float' };
  } else {
    scalar = { kind: 'scalar', name: 'Any' };
  }
  return hasNull ? wrapOptional(scalar) : scalar;
}

/**
 * 合并一组对象为单个具名类：取键的并集，同名字段递归合并类型。
 *
 * 字段仅在部分对象中出现时标记 absent（dataclass 给 Optional + None 默认值，
 * TypedDict 标 NotRequired）；规范化后重名字段在类内去重。
 *
 * @param objects - 需要合并的对象集合
 * @param baseName - 该类期望的基础名称
 * @param context - 推断上下文
 * @returns 生成的类类型节点
 */
function collectClass(
  objects: Record<string, unknown>[],
  baseName: string,
  context: InferContext,
): PyType {
  const name = reserveClassName(baseName, context);
  // 先占位以保证输出顺序为「父类在前」，随后再回填字段表
  context.classes.set(name, []);

  const keys: string[] = [];
  const seenKeys = new Set<string>();
  for (const object of objects) {
    for (const key of Object.keys(object)) {
      if (!seenKeys.has(key)) {
        seenKeys.add(key);
        keys.push(key);
      }
    }
  }

  const fields: FieldSpec[] = [];
  const usedFieldNames = new Set<string>();
  for (const key of keys) {
    const presentValues: unknown[] = [];
    let absent = false;
    for (const object of objects) {
      if (Object.prototype.hasOwnProperty.call(object, key)) {
        presentValues.push(object[key]);
      } else {
        absent = true;
      }
    }

    const fieldBase = toPythonFieldName(key);
    let fieldName = fieldBase;
    let fieldSuffix = 2;
    while (usedFieldNames.has(fieldName)) {
      fieldName = `${fieldBase}_${fieldSuffix}`;
      fieldSuffix += 1;
    }
    usedFieldNames.add(fieldName);

    // null 参与合并时类型已含 Optional；对象缺失导致的 Optional 在渲染期按风格处理
    const type = mergeTypes(presentValues, `${name}${toPythonClassName(key)}`, context);
    fields.push({ key, name: fieldName, type, absent });
  }

  context.classes.set(name, fields);
  return { kind: 'class', name };
}

/**
 * 把类型节点渲染为 Python 类型文本。
 *
 * @param type - 类型节点
 * @param state - 渲染状态（登记 typing 导入）
 * @returns 类型文本
 */
function renderType(type: PyType, state: RenderState): string {
  switch (type.kind) {
    case 'scalar':
      if (type.name === 'Any') {
        state.needAny = true;
      }
      return type.name;
    case 'optional':
      state.needOptional = true;
      return `Optional[${renderType(type.element, state)}]`;
    case 'list':
      return type.element ? `list[${renderType(type.element, state)}]` : 'list';
    case 'class':
      return type.name;
  }
}

/**
 * 构造 list 字面量的推导式表达式（供 from_dict 使用）。
 *
 * @param element - 数组元素类型
 * @param source - 源数据表达式
 * @param state - 渲染状态
 * @returns 形如 [Cls.from_dict(item) for item in source] 的表达式
 */
function renderListExpr(element: PyType, source: string, state: RenderState): string {
  if (element.kind === 'list') {
    const inner = element.element
      ? renderListExpr(element.element, 'item', state)
      : 'list(item)';
    return `[${inner} for item in ${source}]`;
  }
  if (element.kind === 'class') {
    return `[${element.name}.from_dict(item) for item in ${source}]`;
  }
  if (element.kind === 'optional') {
    return `[None if item is None else ${renderScalarValueExpr(element.element, 'item', state)} for item in ${source}]`;
  }
  return `[item for item in ${source}]`;
}

/**
 * 构造非空标量 / 类值的转换表达式。
 *
 * @param type - 值类型（不含 optional / null 分支）
 * @param source - 源数据表达式
 * @param state - 渲染状态
 * @returns 转换表达式
 */
function renderScalarValueExpr(type: PyType, source: string, state: RenderState): string {
  if (type.kind === 'class') {
    return `${type.name}.from_dict(${source})`;
  }
  if (type.kind === 'list') {
    return type.element ? renderListExpr(type.element, source, state) : source;
  }
  return source;
}

/**
 * 构造单个字段的 from_dict 取值表达式（含 None 守卫）；
 * 可缺省字段统一走 dict.get，键缺失时得到 None。
 *
 * @param field - 字段描述
 * @param state - 渲染状态
 * @returns 字段赋值右侧表达式
 */
function renderFromDictExpr(field: FieldSpec, state: RenderState): string {
  // dataclass 中可缺省字段已包装 Optional（见 renderDataclass）；
  // null 合并产生的 optional 与缺失产生的 optional 统一处理
  const source = field.absent ? `d.get("${field.key}")` : `d["${field.key}"]`;
  if (field.type.kind === 'optional') {
    return `None if ${source} is None else ${renderScalarValueExpr(field.type.element, source, state)}`;
  }
  if (field.absent) {
    return `None if ${source} is None else ${renderScalarValueExpr(field.type, source, state)}`;
  }
  return renderScalarValueExpr(field.type, source, state);
}

/**
 * 渲染类的 from_dict 方法。
 *
 * @param name - 类名
 * @param fields - 字段表（已按必填在前排序）
 * @param state - 渲染状态
 * @returns 方法源码块
 */
function renderFromDictMethod(name: string, fields: FieldSpec[], state: RenderState): string {
  const lines: string[] = [
    '    @classmethod',
    `    def from_dict(cls, d: dict) -> "${name}":`,
    '        return cls(',
  ];
  for (const field of fields) {
    lines.push(`            ${field.name}=${renderFromDictExpr(field, state)},`);
  }
  lines.push('        )');
  return lines.join('\n');
}

/**
 * 渲染根类的 to_dict 方法（基于 dataclasses.asdict 递归转换）。
 *
 * @returns 方法源码块
 */
function renderToDictMethod(): string {
  return ['    def to_dict(self) -> dict:', '        return asdict(self)'].join('\n');
}

/**
 * 渲染一个 @dataclass 类定义。
 *
 * 必填字段在前、带 None 默认值的可选字段在后；无字段时输出 pass。
 *
 * @param name - 类名
 * @param fields - 字段表
 * @param helpers - 是否生成辅助方法
 * @param isRoot - 是否为根类（根类额外生成 to_dict）
 * @param state - 渲染状态
 * @returns 类源码块
 */
function renderDataclass(
  name: string,
  fields: FieldSpec[],
  helpers: boolean,
  isRoot: boolean,
  state: RenderState,
): string {
  const required = fields.filter((field) => !field.absent);
  const optional = fields.filter((field) => field.absent);
  const ordered = [...required, ...optional];

  const lines: string[] = ['@dataclass', `class ${name}:`];
  if (ordered.length === 0) {
    lines.push('    pass');
  } else {
    for (const field of ordered) {
      // 可缺省字段在 dataclass 中统一表达为 Optional[T] = None
      const fieldType = field.absent ? wrapOptional(field.type) : field.type;
      const annotation = renderType(fieldType, state);
      const suffix = field.absent ? ' = None' : '';
      lines.push(`    ${field.name}: ${annotation}${suffix}`);
    }
  }

  if (helpers) {
    lines.push('');
    lines.push(renderFromDictMethod(name, ordered, state));
    if (isRoot) {
      lines.push('');
      lines.push(renderToDictMethod());
    }
  }
  return lines.join('\n');
}

/**
 * 渲染一个 TypedDict 类定义。
 *
 * 缺失键标记 NotRequired；null 仍以 Optional 表达。
 *
 * @param name - 类名
 * @param fields - 字段表
 * @param state - 渲染状态
 * @returns 类源码块
 */
function renderTypedDict(name: string, fields: FieldSpec[], state: RenderState): string {
  const lines: string[] = [`class ${name}(TypedDict):`];
  if (fields.length === 0) {
    lines.push('    pass');
  } else {
    for (const field of fields) {
      let annotation = renderType(field.type, state);
      if (field.absent) {
        state.needNotRequired = true;
        annotation = `NotRequired[${annotation}]`;
      }
      lines.push(`    ${field.name}: ${annotation}`);
    }
  }
  return lines.join('\n');
}

/**
 * 解析 JSON 文本并生成 Python @dataclass 或 TypedDict 定义。
 *
 * 整数推断为 int、浮点为 float、null 参与 Optional 合并，空数组退化为裸 list，
 * 嵌套对象提升为顶层具名类。输入为空或纯空白时返回空串。
 *
 * @param jsonText - JSON 文本
 * @param options - 可选配置（根类名 className、风格 style、辅助方法 helpers）
 * @returns 生成的 Python 源码与类数量
 * @throws 当输入不是合法 JSON 或根类名不是合法 Python 标识符时抛出可读错误
 */
export function generatePythonDataclass(
  jsonText: string,
  options: GenerateOptions = {},
): GenerateResult {
  const trimmed = jsonText.trim();
  if (trimmed === '') {
    return { output: '', classCount: 0 };
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(trimmed);
  } catch (caught) {
    const detail = caught instanceof Error ? caught.message : String(caught);
    throw new Error('JSON 解析失败：' + detail);
  }

  const rawRootName = (options.className ?? DEFAULT_CLASS_NAME).trim() || DEFAULT_CLASS_NAME;
  if (!IDENTIFIER_PATTERN.test(rawRootName)) {
    throw new Error('根类名必须是合法的 Python 标识符：' + rawRootName);
  }
  // 规范化为 PascalCase（my_model → MyModel）
  const rootName = toPythonClassName(rawRootName);

  const style: OutputStyle = options.style ?? 'dataclass';
  const helpers = style === 'dataclass' ? (options.helpers ?? true) : false;

  const context = createInferContext();
  const state: RenderState = {
    needAny: false,
    needOptional: false,
    needNotRequired: false,
  };

  let rootIsClass = false;
  let aliasType: PyType | null = null;
  if (isPlainObject(parsed)) {
    collectClass([parsed], rootName, context);
    rootIsClass = true;
  } else if (Array.isArray(parsed)) {
    // 非对象根：先占位根名，避免与数组元素类重名；mergeTypes 已包一层 list
    context.usedClassNames.add(rootName);
    aliasType = mergeTypes([parsed], `${rootName}Item`, context);
  } else {
    context.usedClassNames.add(rootName);
    aliasType = inferScalar(parsed);
  }

  // 先渲染全部类体以收集 typing 导入需求，再组装文件头部
  const classBlocks: string[] = [];
  for (const name of context.classes.keys()) {
    const fields = context.classes.get(name) ?? [];
    if (style === 'dataclass') {
      classBlocks.push(renderDataclass(name, fields, helpers, name === rootName, state));
    } else {
      classBlocks.push(renderTypedDict(name, fields, state));
    }
  }

  const blocks: string[] = [];
  if (style === 'dataclass') {
    blocks.push('from __future__ import annotations');
    blocks.push('');
    const dataclassImports = ['dataclass'];
    if (helpers && rootIsClass) {
      dataclassImports.unshift('asdict');
    }
    blocks.push(`from dataclasses import ${dataclassImports.join(', ')}`);
    const typingImports: string[] = [];
    if (state.needAny) {
      typingImports.push('Any');
    }
    if (state.needOptional) {
      typingImports.push('Optional');
    }
    if (typingImports.length > 0) {
      blocks.push(`from typing import ${typingImports.join(', ')}`);
    }
    blocks.push('');
    blocks.push('# 由 JSON 自动生成：null 字段以 Optional 表达，空数组退化为 list。');
  } else {
    const typingImports = ['TypedDict'];
    if (state.needAny) {
      typingImports.push('Any');
    }
    if (state.needOptional) {
      typingImports.push('Optional');
    }
    if (state.needNotRequired) {
      typingImports.push('NotRequired');
    }
    const suffix = state.needNotRequired ? '  # NotRequired 需 Python 3.11+' : '';
    blocks.push(`from typing import ${typingImports.join(', ')}${suffix}`);
    blocks.push('');
    blocks.push('# 由 JSON 自动生成：可能缺失的键标记为非必填，空数组退化为 list。');
  }

  for (const block of classBlocks) {
    blocks.push('');
    blocks.push(block);
  }

  if (aliasType !== null) {
    blocks.push('');
    blocks.push(`${rootName} = ${renderType(aliasType, state)}`);
  }

  return { output: blocks.join('\n'), classCount: context.classes.size };
}

/**
 * 推断根标量 JSON 值的 Python 类型。
 *
 * @param value - 非对象、非数组的 JSON 标量（含 null）
 * @returns 标量类型节点
 */
function inferScalar(value: unknown): PyType {
  if (value === null) {
    return { kind: 'scalar', name: 'None' };
  }
  if (typeof value === 'number') {
    return { kind: 'scalar', name: Number.isInteger(value) ? 'int' : 'float' };
  }
  if (typeof value === 'string') {
    return { kind: 'scalar', name: 'str' };
  }
  return { kind: 'scalar', name: 'bool' };
}
